namespace CaeriusNet.Generator.Tvp;

/// <summary>
///     Pure source emitter for <see cref="TvpModel" />. Outputs an <see cref="ITvpMapper{T}" /> implementation
///     that streams rows through a single reused <c>SqlDataRecord</c>.
/// </summary>
internal static class TvpEmitter
{
    internal static string Emit(TvpModel model)
    {
        var capacity = 600 + model.Columns.Count * 120;
        var sb = new StringBuilder(capacity);

        AppendHeader(sb);
        AppendUsings(sb);
        AppendNamespace(sb, model.Namespace);
        AppendBody(sb, model);

        return sb.ToString();
    }

    private static void AppendHeader(StringBuilder sb)
    {
        sb.AppendLine("// <auto-generated by CaeriusNet.Generator />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable CS1591 // Missing XML comment for publicly visible type or member");
        sb.AppendLine();
    }

    private static void AppendUsings(StringBuilder sb)
    {
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Immutable;");
        sb.AppendLine("using System.Data;");
        sb.AppendLine("using System.CodeDom.Compiler;");
        sb.AppendLine("using Microsoft.Data.SqlClient.Server;");
        sb.AppendLine("using CaeriusNet.Mappers;");
        sb.AppendLine();
    }

    private static void AppendNamespace(StringBuilder sb, string ns)
    {
        if (string.IsNullOrEmpty(ns)) return;
        sb.Append("namespace ").Append(ns).AppendLine(";");
        sb.AppendLine();
    }

    private static void AppendBody(StringBuilder sb, TvpModel model)
    {
        var typeName = CSharpIdentifier.Escape(model.TypeName);
        sb.Append(model.AccessibilityKeyword).Append(' ').Append(model.DeclarationKeywords).Append(' ')
            .Append(typeName)
            .Append(" : ITvpMapper<").Append(typeName).AppendLine(">");
        sb.AppendLine("{");

        sb.AppendLine("    /// <summary>Gets the SQL Server type name for this TVP.</summary>");
        sb.Append("    public static string SqlTypeName => ")
            .Append(ToStringLiteral(model.Schema + "." + model.TvpName)).AppendLine(";");
        sb.AppendLine();

        AppendMetaDataField(sb, model.Columns);
        AppendMapMethod(sb, model, typeName);

        sb.AppendLine("}");
    }

    private static void AppendMetaDataField(StringBuilder sb, EquatableArray<ColumnModel> columns)
    {
        sb.AppendLine("    private static readonly SqlMetaData[] _tvpMetaData =");
        sb.AppendLine("    [");

        for (var i = 0; i < columns.Count; i++)
        {
            var trailing = i < columns.Count - 1 ? "," : string.Empty;
            sb.Append("        ").Append(columns[i].SqlMetaDataConstructor).AppendLine(trailing);
        }

        sb.AppendLine("    ];");
        sb.AppendLine("    private static readonly ImmutableArray<SqlMetaData> _metadata = [.. _tvpMetaData];");
        sb.AppendLine();
        sb.AppendLine("    public static ImmutableArray<SqlMetaData> Metadata => _metadata;");
        sb.AppendLine();
    }

    private static void AppendMapMethod(StringBuilder sb, TvpModel model, string typeName)
    {
        sb.AppendLine("    /// <summary>Creates the reusable record used while streaming rows.</summary>");
        sb.AppendLine(
            $"    [GeneratedCode(\"{GeneratorMetadata.ToolName}\", \"{GeneratorMetadata.Version}\")]");
        sb.AppendLine("    public static SqlDataRecord CreateRecord() => new(_tvpMetaData);");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>Writes one row into a record owned by the runtime.</summary>");
        sb.AppendLine(
            $"    [GeneratedCode(\"{GeneratorMetadata.ToolName}\", \"{GeneratorMetadata.Version}\")]");
        sb.Append("    public static void WriteRow(SqlDataRecord record, ")
            .Append(typeName).AppendLine(" item)");
        sb.AppendLine("    {");
        sb.AppendLine("        ArgumentNullException.ThrowIfNull(record);");
        for (var i = 0; i < model.Columns.Count; i++)
            sb.Append("        ").AppendLine(BuildSetCall(model.Columns[i]));
        sb.AppendLine("    }");
    }

    /// <summary>
    ///     Returns a single statement (terminated by <c>;</c>) that writes <c>item.{Name}</c> onto the reused
    ///     <c>SqlDataRecord</c>. Nullable parameters generate a guard that calls <c>SetDBNull</c>.
    /// </summary>
    private static string BuildSetCall(ColumnModel column)
    {
        var ordinal = column.OrdinalPosition;
        var valueAccess = column.IsNullableValueType ? ".Value" : string.Empty;
        var setMethod = column.ReaderMethod.Replace("Get", "Set");
        var assignmentTarget = "item." + CSharpIdentifier.Escape(column.Name);

        var setExpr = column.Kind switch
        {
            ColumnKind.DateOnly =>
                $"record.SetDateTime({ordinal}, {assignmentTarget}{valueAccess}.ToDateTime(global::System.TimeOnly.MinValue))",
            ColumnKind.TimeOnly =>
                $"record.SetTimeSpan({ordinal}, {assignmentTarget}{valueAccess}.ToTimeSpan())",
            ColumnKind.ByteArray =>
                $"record.SetValue({ordinal}, {assignmentTarget})",
            ColumnKind.Char =>
                $"record.SetChar({ordinal}, {assignmentTarget}{valueAccess})",
            ColumnKind.Half =>
                $"record.SetFloat({ordinal}, (float){assignmentTarget}{valueAccess})",
            ColumnKind.SqlDecimal =>
                $"record.SetSqlDecimal({ordinal}, {assignmentTarget}{valueAccess})",
            ColumnKind.UInt64 =>
                $"record.SetDecimal({ordinal}, checked((decimal){assignmentTarget}{valueAccess}))",
            ColumnKind.Enum when column.EnumUnderlyingType is not null =>
                $"record.{setMethod}({ordinal}, ({column.EnumUnderlyingType}){assignmentTarget}{valueAccess})",
            _ => $"record.{setMethod}({ordinal}, {assignmentTarget}{valueAccess})"
        };

        return column.IsNullable
            ? $"if ({assignmentTarget} is null) record.SetDBNull({ordinal}); else {setExpr};"
            : $"{setExpr};";
    }

    private static string ToStringLiteral(string value)
    {
        var sb = new StringBuilder(value.Length + 2);
        sb.Append('"');
        foreach (var ch in value)
            switch (ch)
            {
                case '\\':
                    sb.Append(@"\\");
                    break;
                case '"':
                    sb.Append("\\\"");
                    break;
                case '\0':
                    sb.Append(@"\0");
                    break;
                case '\a':
                    sb.Append(@"\a");
                    break;
                case '\b':
                    sb.Append(@"\b");
                    break;
                case '\f':
                    sb.Append(@"\f");
                    break;
                case '\n':
                    sb.Append(@"\n");
                    break;
                case '\r':
                    sb.Append(@"\r");
                    break;
                case '\t':
                    sb.Append(@"\t");
                    break;
                case '\v':
                    sb.Append(@"\v");
                    break;
                default:
                    if (char.IsControl(ch))
                        sb.Append(@"\u")
                            .Append(((int)ch).ToString("x4", CultureInfo.InvariantCulture));
                    else
                        sb.Append(ch);
                    break;
            }

        sb.Append('"');
        return sb.ToString();
    }
}
